-- Isolate confidential safeguarding casework from the general VSI application login.
-- Provision the LOGIN credential separately in Neon. Never commit its password.
CREATE ROLE vsi_safeguarding_access NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;

CREATE TABLE public.safeguarding_login_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX safeguarding_login_attempts_ip_created_idx
  ON public.safeguarding_login_attempts (ip_hash, created_at DESC);

ALTER TABLE public.safeguarding_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safeguarding_case_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safeguarding_audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safeguarding_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safeguarding_login_attempts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS vsi_safeguarding_access_all ON public.safeguarding_reports;
CREATE POLICY vsi_safeguarding_access_all ON public.safeguarding_reports
  FOR ALL TO vsi_safeguarding_access USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS vsi_safeguarding_legacy_access ON public.safeguarding_reports;
CREATE POLICY vsi_safeguarding_legacy_access ON public.safeguarding_reports
  FOR ALL TO vsi_app USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS vsi_safeguarding_ingest_insert ON public.safeguarding_reports;
CREATE POLICY vsi_safeguarding_ingest_insert ON public.safeguarding_reports
  FOR INSERT TO vsi_safeguarding_ingest WITH CHECK (true);

